// Helper functions for easy lookup across the entire platform
export function getDomainById(domainId: string): TalentDomain | undefined {
  return TALENT_DOMAINS.find(d => d.id === domainId);
}

export function getTalentById(talentId: string) {
  for (const domain of TALENT_DOMAINS) {
    const found = domain.talents.find(t => t.id === talentId);
    if (found) return { talent: found, domain };
  }
  return undefined;
}

export function getAllTalents() {
  return TALENT_DOMAINS.flatMap(d => d.talents);
}

export function getTalentsByDomain(domainId: string) {
  const domain = getDomainById(domainId);
  return domain ? domain.talents : [];
}

export function searchTalents(query: string) {
  const q = query.toLowerCase().trim();
  if (!q) return getAllTalents();
  return getAllTalents().filter(t => 
    t.name.toLowerCase().includes(q) ||
    t.shortDescription.toLowerCase().includes(q) ||
    t.popularTags.some(tag => tag.toLowerCase().includes(q)) ||
    t.commonSkills.some(skill => skill.toLowerCase().includes(q))
  );
}
